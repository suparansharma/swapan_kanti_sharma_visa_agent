// Helper to format any raw visa type or INDIAN_VISA_TYPES entry nicely
export function formatVisaTypeDisplay(v: string): string {
  if (!v) return "";
  const found = STRUCTURED_INDIAN_VISA_TYPES.find((item) => item.value === v);
  if (found) {
    return found.title;
  }
  if (v.length > 50) {
    const parts = v.split(" - ");
    if (parts.length > 1) {
      return parts[0];
    }
  }
  return v;
}

